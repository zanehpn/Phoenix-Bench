#!/usr/bin/env python3
"""Collect Verilator coverage only for lines added by a patch.

The script intersects unified-diff added lines in patches/<case>.patch with
coverage points generated by testbench_verilator/<case>/coverage.info and
coverage.dat.  It reports only fixed-version patch code that still exists as a
new-file line.  Deleted lines are counted separately because they cannot be hit
in the fixed design.
"""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent
Exclusions = set[tuple[str, str, int]]


def load_exclusions(csv_path: str | None) -> Exclusions:
    if not csv_path:
        return set()
    path = ROOT / csv_path
    if not path.exists():
        raise FileNotFoundError(path)
    excluded: Exclusions = set()
    with path.open(newline="") as f:
        for row in csv.DictReader(f):
            excluded.add((row["case"], row["file"], int(row["line"])))
    return excluded


def is_excluded(exclusions: Exclusions, case: str, rel: str, line_no: int) -> bool:
    return (case, rel, line_no) in exclusions


def parse_patch(patch_path: Path) -> tuple[dict[str, set[int]], int]:
    added: dict[str, set[int]] = {}
    deleted = 0
    current: str | None = None
    new_line: int | None = None

    for raw in patch_path.read_text(errors="replace").splitlines():
        m = re.match(r"^\+\+\+ b/(.+)$", raw)
        if m:
            current = m.group(1)
            added.setdefault(current, set())
            new_line = None
            continue
        if raw.startswith("+++ /dev/null"):
            current = None
            new_line = None
            continue
        m = re.match(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@", raw)
        if m:
            new_line = int(m.group(1))
            continue
        if current is None or new_line is None:
            continue
        if raw.startswith("+") and not raw.startswith("+++"):
            added[current].add(new_line)
            new_line += 1
        elif raw.startswith("-") and not raw.startswith("---"):
            deleted += 1
        else:
            # Context lines, including "\ No newline..." markers, advance only
            # when they are real hunk content.
            if not raw.startswith("\\"):
                new_line += 1

    return {k: v for k, v in added.items() if v}, deleted


def rel_for_source(source: str, patch_files: set[str]) -> str | None:
    normalized = source.replace("\\", "/")
    for rel in patch_files:
        if normalized == rel or normalized.endswith("/" + rel):
            return rel
    return None


def parse_lcov(info_path: Path, patch_lines: dict[str, set[int]], case: str, exclusions: Exclusions) -> tuple[int, int]:
    if not info_path.exists() or not info_path.stat().st_size:
        return 0, 0
    current: str | None = None
    patch_files = set(patch_lines)
    hit = total = 0
    seen: set[tuple[str, int]] = set()

    for raw in info_path.read_text(errors="replace").splitlines():
        if raw.startswith("SF:"):
            current = rel_for_source(raw[3:], patch_files)
            continue
        if current is None or not raw.startswith("DA:"):
            continue
        parts = raw[3:].split(",")
        if len(parts) < 2:
            continue
        try:
            line_no = int(parts[0])
            count = int(parts[1])
        except ValueError:
            continue
        key = (current, line_no)
        if (
            line_no in patch_lines[current]
            and key not in seen
            and not is_excluded(exclusions, case, current, line_no)
        ):
            seen.add(key)
            total += 1
            if count > 0:
                hit += 1
    return hit, total


def collect_lcov_missing(case: str, exclusions: Exclusions) -> list[dict[str, str | int]]:
    patch_path = ROOT / "patches" / f"{case}.patch"
    case_dir = ROOT / "testbench_verilator" / case
    added, _ = parse_patch(patch_path)

    info_path = case_dir / "coverage.info"
    if not info_path.exists():
        info_path = case_dir / "verilator_fixed_coverage.info"
    if not info_path.exists():
        return []

    patch_files = set(added)
    counts: dict[tuple[str, int], int] = {}
    current: str | None = None
    for raw in info_path.read_text(errors="replace").splitlines():
        if raw.startswith("SF:"):
            current = rel_for_source(raw[3:], patch_files)
            continue
        if current is None or not raw.startswith("DA:"):
            continue
        parts = raw[3:].split(",")
        if len(parts) < 2:
            continue
        try:
            counts[(current, int(parts[0]))] = int(parts[1])
        except ValueError:
            continue

    missing: list[dict[str, str | int]] = []
    for rel, lines in added.items():
        src = case_dir / "snapshot_scratch" / rel
        text = src.read_text(errors="replace").splitlines() if src.exists() else []
        for line_no in sorted(lines):
            key = (rel, line_no)
            if key in counts and counts[key] == 0 and not is_excluded(exclusions, case, rel, line_no):
                source_line = text[line_no - 1].strip() if line_no - 1 < len(text) else ""
                missing.append({
                    "case": case,
                    "file": rel,
                    "line": line_no,
                    "text": source_line,
                })
    return missing


def parse_coverage_dat(dat_path: Path, patch_lines: dict[str, set[int]], case: str, exclusions: Exclusions) -> dict[str, list[int]]:
    stats = {
        "all": [0, 0],
        "line": [0, 0],
        "toggle": [0, 0],
        "branch": [0, 0],
    }
    if not dat_path.exists() or not dat_path.stat().st_size:
        return stats

    patch_files = set(patch_lines)
    file_re = re.compile(r"\x01f\x02([^\x01]+)")
    line_re = re.compile(r"\x01l\x02(\d+)")
    page_re = re.compile(r"\x01page\x02([^\x01]+)")

    for raw in dat_path.read_text(errors="replace").splitlines():
        if not raw.startswith("C "):
            continue
        fm = file_re.search(raw)
        lm = line_re.search(raw)
        pm = page_re.search(raw)
        if not fm or not lm or not pm:
            continue
        rel = rel_for_source(fm.group(1), patch_files)
        if rel is None:
            continue
        line_no = int(lm.group(1))
        if line_no not in patch_lines[rel]:
            continue
        if is_excluded(exclusions, case, rel, line_no):
            continue
        page = pm.group(1)
        kind = "line" if "v_line" in page else "toggle" if "v_toggle" in page else "branch" if "v_branch" in page else None
        if kind is None:
            continue
        try:
            count = int(raw.rsplit(" ", 1)[1])
        except ValueError:
            count = 0
        hit = 1 if count > 0 else 0
        for bucket in ("all", kind):
            stats[bucket][1] += 1
            stats[bucket][0] += hit
    return stats


def pct(hit: int, total: int) -> str:
    return "NA" if total == 0 else f"{hit / total * 100:.2f}"


def collect_case(case: str, exclusions: Exclusions) -> dict[str, str | int]:
    patch_path = ROOT / "patches" / f"{case}.patch"
    case_dir = ROOT / "testbench_verilator" / case
    added, deleted = parse_patch(patch_path)

    info_path = case_dir / "coverage.info"
    if not info_path.exists():
        info_path = case_dir / "verilator_fixed_coverage.info"
    dat_path = case_dir / "coverage.dat"
    if not dat_path.exists():
        dat_path = case_dir / "verilator_fixed_coverage.dat"

    lcov_hit, lcov_total = parse_lcov(info_path, added, case, exclusions)
    dat_stats = parse_coverage_dat(dat_path, added, case, exclusions)

    row: dict[str, str | int] = {
        "case": case,
        "patch_files": len(added),
        "patch_added_lines": sum(len(v) for v in added.values()),
        "patch_deleted_lines": deleted,
        "lcov_line_hit": lcov_hit,
        "lcov_line_total": lcov_total,
        "lcov_line_pct": pct(lcov_hit, lcov_total),
    }
    for key, prefix in [
        ("all", "dat_all"),
        ("line", "dat_line"),
        ("toggle", "dat_toggle"),
        ("branch", "dat_branch"),
    ]:
        hit, total = dat_stats[key]
        row[f"{prefix}_hit"] = hit
        row[f"{prefix}_total"] = total
        row[f"{prefix}_pct"] = pct(hit, total)
    return row


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("cases", nargs="*", help="case names; defaults to all cases with coverage files")
    parser.add_argument("--csv", default="verilator_patch_coverage_results.csv")
    parser.add_argument("--missing-csv", help="optional CSV of unhit patch-added LCOV lines")
    parser.add_argument("--exclude-csv", help="optional CSV of unreachable patch lines to exclude from coverage totals")
    args = parser.parse_args()
    exclusions = load_exclusions(args.exclude_csv)

    if args.cases:
      cases = args.cases
    else:
      cases = sorted(
          p.name
          for p in (ROOT / "testbench_verilator").iterdir()
          if p.is_dir()
          and (
              (p / "coverage.info").exists()
              or (p / "verilator_fixed_coverage.info").exists()
              or (p / "coverage.dat").exists()
              or (p / "verilator_fixed_coverage.dat").exists()
          )
          and (ROOT / "patches" / f"{p.name}.patch").exists()
      )

    rows = [collect_case(case, exclusions) for case in cases]
    fields = [
        "case",
        "patch_files",
        "patch_added_lines",
        "patch_deleted_lines",
        "lcov_line_hit",
        "lcov_line_total",
        "lcov_line_pct",
        "dat_all_hit",
        "dat_all_total",
        "dat_all_pct",
        "dat_line_hit",
        "dat_line_total",
        "dat_line_pct",
        "dat_toggle_hit",
        "dat_toggle_total",
        "dat_toggle_pct",
        "dat_branch_hit",
        "dat_branch_total",
        "dat_branch_pct",
    ]
    out_path = ROOT / args.csv
    with out_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)

    print(",".join(fields))
    for row in rows:
        print(",".join(str(row[field]) for field in fields))
    print(f"\nSaved: {out_path}")

    if args.missing_csv:
        missing_fields = ["case", "file", "line", "text"]
        missing_path = ROOT / args.missing_csv
        missing_rows = [item for case in cases for item in collect_lcov_missing(case, exclusions)]
        with missing_path.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=missing_fields)
            writer.writeheader()
            writer.writerows(missing_rows)
        print(f"Missing LCOV patch lines: {len(missing_rows)}")
        print(f"Saved missing: {missing_path}")


if __name__ == "__main__":
    main()
